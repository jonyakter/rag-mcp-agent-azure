//         The Agent embeds the query with OpenAI BEFORE calling the MCP server.
//         The MCP server never touches OpenAI — it only does cosine search.

using System.Collections.Generic;

namespace MyCloudProject.Common
{
    /// <summary>
    /// Request sent from the Agent (MyCloudProject) to the MCP server.
    /// The agent must embed the query FIRST (via OpenAI) and pass the
    /// resulting vector here. The MCP server performs cosine similarity
    /// against the SQL database and returns ranked results.
    /// </summary>
    public class McpRecommendRequest
    {
        /// <summary>
        /// Pre-computed embedding vector for the query.
        /// Generated by the Agent using OpenAiEmbeddingService BEFORE this call.
        /// Must match the dimensionality of vectors stored in the SQL database
        /// (e.g. 1536 for text-embedding-3-small).
        /// </summary>
        public required float[] QueryVector { get; set; }

        /// <summary>
        /// The original natural-language query string.
        /// Not used for similarity search — kept for logging and result metadata only.
        /// </summary>
        public required string QueryText { get; set; }

        /// <summary>Optional category filter (e.g. "movies"). Null or empty = all categories.</summary>
        public string? Category { get; set; }

        /// <summary>How many top matches to return. Default: 5.</summary>
        public int TopN { get; set; } = 5;
    }

    /// <summary>
    /// A single recommended item returned by the MCP server.
    /// </summary>
    public class McpRecommendationItem
    {
        /// <summary>1-based rank in the result list.</summary>
        public int Rank { get; set; }

        /// <summary>Display title of the recommended item.</summary>
        public required string Title { get; set; }

        /// <summary>Source file the record came from.</summary>
        public required string FileName { get; set; }

        /// <summary>Category the record belongs to.</summary>
        public required string Category { get; set; }

        /// <summary>Raw cosine similarity score (0–1).</summary>
        public double Score { get; set; }
    }

    /// <summary>
    /// Response returned by the MCP server for a recommendation request.
    /// </summary>
    public class McpRecommendResponse
    {
        /// <summary>The original query text (echoed from the request for logging).</summary>
        public required string QueryText { get; set; }

        /// <summary>Title of the highest-ranked match, or null when there are no results.</summary>
        public string? BestMatch { get; set; }

        /// <summary>Cosine similarity score of the best match (0–1).</summary>
        public double BestScore { get; set; }

        /// <summary>All ranked recommendations.</summary>
        public List<McpRecommendationItem> Items { get; set; } = new List<McpRecommendationItem>();

        /// <summary>Human-readable formatted result text for the output file.</summary>
        public required string FormattedText { get; set; }
    }
}